-- auto reread
vim.opt.autoread = true
-- 当焦点回到 Neovim 或切换缓冲区时检查文件变更
vim.api.nvim_create_autocmd({ "FocusGained", "BufEnter", "CursorHold", "CursorHoldI" }, {
  pattern = "*",
  callback = function()
    if vim.fn.mode() ~= 'c' then
      vim.cmd('checktime')
    end
  end,
})

-- 文件变更时显示通知
vim.api.nvim_create_autocmd("FileChangedShellPost", {
  pattern = "*",
  callback = function()
    vim.notify("文件已在外部被修改，已重新加载", vim.log.levels.WARN)
  end,
})

